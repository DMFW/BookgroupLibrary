        protected void lbtnInsertGroupMember_Click(object sender, EventArgs e)
        {

            Page.Validate(); // Have to do this manually for some reason as CausesValidation not working in the footer

            if (Page.IsValid)
            {
                SqlDataSource GroupMembers = SqlDataSourceGroupMembers;
                GridViewRow gvrInsertRow = grdGroupMembers.FooterRow;

                GroupMembers.InsertParameters["FirstName"].DefaultValue = (GetGridViewControlValue(gvrInsertRow, "txtFirstName") != string.Empty) ? GetGridViewControlValue(gvrInsertRow, "txtFirstName") : "";
                GroupMembers.InsertParameters["LastName"].DefaultValue = (GetGridViewControlValue(gvrInsertRow, "txtLastName") != string.Empty) ? GetGridViewControlValue(gvrInsertRow, "txtLastName") : "";
                GroupMembers.InsertParameters["EmailAddress"].DefaultValue = GetGridViewControlValue(gvrInsertRow, "txtEmailAddress");
                GroupMembers.InsertParameters["DateOfBirth"].DefaultValue = GetGridViewControlValue(gvrInsertRow, "txtDOB");

                GroupMembers.InsertParameters["LoginName"].DefaultValue = (GetGridViewControlValue(gvrInsertRow, "txtLoginName") != string.Empty) ? GetGridViewControlValue(gvrInsertRow, "txtLoginName") : "";
                GroupMembers.InsertParameters["Sex"].DefaultValue = GetGridViewControlValue(gvrInsertRow, "ddlSex");
                GroupMembers.InsertParameters["Administrator"].DefaultValue = GetGridViewControlValue(gvrInsertRow, "chkAdministrator");
                GroupMembers.InsertParameters["IsLockedOut"].DefaultValue = GetGridViewControlValue(gvrInsertRow, "chkLocked");

                GroupMembers.Insert();

                ShowFooterInsertControls(false);
            }
        }

        private string GetGridViewControlValue(GridViewRow row, string sControlName)
        {
            string sFieldValue = string.Empty;

            Control gridEditControl = row.FindControl(sControlName);

            if (gridEditControl == null)
            {
                throw new Exception("GetGridViewRowTextValue: could not find " + sControlName + " control!");
            }

            if (gridEditControl is TextBox)
            {
                TextBox txtEditControl = (TextBox)gridEditControl;
                sFieldValue = txtEditControl.Text.Trim();
                return sFieldValue;
            }

            if (gridEditControl is CheckBox)
            {
                CheckBox chkEditControl = (CheckBox)gridEditControl;
                sFieldValue = chkEditControl.Checked.ToString();
                return sFieldValue;
            }

            if (gridEditControl is DropDownList)
            {
                DropDownList ddlEditControl = (DropDownList)gridEditControl;
                sFieldValue = ddlEditControl.SelectedValue;
                return sFieldValue;
            }

            return "";

        }

