        protected void grdGroupMembers_SelectedIndexChanging(object sender, GridViewSelectEventArgs e)
        {
            int groupMemberID = Int32.Parse(grdGroupMembers.Rows[e.NewSelectedIndex].Cells[1].Text);
            Account.SimpleUserStructure userToSet;

            Button btnChangePassword = (Button)grdGroupMembers.Rows[e.NewSelectedIndex].FindControl("btnChangePassword");

            if (btnChangePassword.Text == "Reset")
            {
                userToSet = UserForPasswordReset(groupMemberID);
                Account.BookgroupMembershipProvider Security = new Account.BookgroupMembershipProvider();
                NameValueCollection WritableConfig = new NameValueCollection(ConfigurationManager.AppSettings);

                string newPwd = userToSet.FirstName + userToSet.LastName.Substring(0, 1);

                Security.Initialize("SiteSecurity", WritableConfig);
                Security.ChangePassword(userToSet.LoginName, "", newPwd);
                AddValidationMessage("User password for account " + userToSet.LoginName + " reset to " + newPwd, "");
            }
            else
            {
                Server.Transfer("../Account/ChangePassword.aspx?GroupMemberID=" + groupMemberID, true);
            }

        }

        protected void grdGroupMembers_DataBound(object sender, EventArgs e)
        {

            // Remove last log in date and password change button in edit or insert mode
