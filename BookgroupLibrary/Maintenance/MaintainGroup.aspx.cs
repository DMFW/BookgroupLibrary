            // already

            if ((grdGroupMembers.EditIndex > -1) | grdGroupMembers.ShowFooter)
            {
                if (!_SignedOnUser.IsAdministrator)
                {
                    grdGroupMembers.Columns[8].Visible = false;
                    grdGroupMembers.Columns[11].Visible = false;
                }
                grdGroupMembers.Columns[9].Visible = false;
                grdGroupMembers.Columns[10].Visible = false;
            }
            else
            {
                grdGroupMembers.Columns[8].Visible = true;
                grdGroupMembers.Columns[9].Visible = true;
                grdGroupMembers.Columns[10].Visible = true;
                grdGroupMembers.Columns[11].Visible = true;
            }
        }

        protected void grdGroupMembers_RowDataBound(object sender, GridViewRowEventArgs e)
        {
           
            if (e.Row.RowType == DataControlRowType.DataRow)
            {
                Button btnChangePassword = (Button)e.Row.FindControl("btnChangePassword");
                LinkButton lnkButtonEdit = (LinkButton)e.Row.FindControl("lnkButtonEdit");
                if (Int32.Parse(e.Row.Cells[1].Text) == _SignedOnUser.GroupMemberID)
                {
                    // All users can change their own password
                    btnChangePassword.Text = "Change";
                }
                else
                {
                    // Administrators can reset other passwords
                    btnChangePassword.Text = "Reset";
                    if (!_SignedOnUser.IsAdministrator)
                    {
                        btnChangePassword.Enabled = false;
                        if (lnkButtonEdit != null)
                        {
                            lnkButtonEdit.Visible = false;
                        }
                    }
                }
            }                  
        }

        public Dictionary<Boolean, string> SexText()
        {
            if (_SexText == null)
            {
                _SexText = new Dictionary<Boolean,string>();
            }

            if (_SexText.Count == 0)
            {
                _SexText.Add(true,"Female");
                _SexText.Add(false,"Male");
            }

            return _SexText;
        }

        private Account.SimpleUserStructure UserForPasswordReset(int groupMemberID)
        {

            Account.SimpleUserStructure userToSet = new Account.SimpleUserStructure();

            string queryString = "SELECT * FROM [GroupMember] WHERE [GroupMember].[GroupMemberID] = @GroupMemberID;";

            using (SqlConnection connection = new SqlConnection(_ConnectionSettings.ConnectionString))
            {
                SqlCommand command = new SqlCommand(queryString, connection);
                command.Parameters.Add(new SqlParameter("@GroupMemberID", groupMemberID));

                connection.Open();

                SqlDataReader reader = command.ExecuteReader();

                reader.Read();

                userToSet.LoginName = (string)reader["LoginName"];
                userToSet.FirstName = (string)reader["FirstName"];
                userToSet.LastName = (string)reader["LastName"];
                userToSet.IsAdministrator = (bool)reader["Administrator"];
                reader.Close();

            }
            return userToSet;
        }

        private void AddValidationMessage(string validationMessage, string validationGroup)
        {
            CustomValidator cv = new CustomValidator();
            cv.ValidationGroup = validationGroup;
            cv.IsValid = false;
            cv.ErrorMessage = validationMessage;
            this.Page.Validators.Add(cv);
        }

        protected void SqlDataSourceGroupMembers_Inserted(object sender, SqlDataSourceStatusEventArgs e)
        {
            if (e.Exception != null)
            {
                AddValidationMessage("The record could not be added for the technical reason '" + e.Exception.Message + "'", "");
                AddValidationMessage("Duplicate log in account names are not allowed. Please check and if this is the reason, try a different one.", "");
                // make the error handled so it does not take over the whole page
                e.ExceptionHandled = true;
            }
        }

