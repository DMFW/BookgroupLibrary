using System;
using System.Collections.Generic;
using System.Linq;
using System.Web;
using System.Web.UI;
using System.Web.UI.WebControls;
using System.Globalization;

namespace BookgroupLibrary
{
    public partial class MaintainAuthors : System.Web.UI.Page
    {

        #region Private/Protected Members

        private Account.SimpleUserStructure _SignedOnUser;

        protected bool _bAllowEditInDetailsView = false;
        protected ViewMode _ViewMode = ViewMode.GridView;
        protected enum ViewMode { Unknown, GridView, DetailsView }

        protected Int32 _AuthorID;

        private Dictionary<Boolean, string> _dctSexText;

        #endregion

        #region Public Properties

        public bool AllowEditInDetailsView
        {
            get { return _bAllowEditInDetailsView; }
            set { _bAllowEditInDetailsView = value; }
        }

        public bool AllowRecordSorting
        {
            get { return grdAuthors.AllowSorting; }
            set { grdAuthors.AllowSorting = value; }
        }

        public bool AllowRecordEditing
        {
            get
            {
                return grdAuthors.AutoGenerateEditButton;
            }

            set
            {
                grdAuthors.AutoGenerateEditButton = value;
            }
        }

        public bool AllowRecordDeleting
        {
            get
            {
                return grdAuthors.AutoGenerateDeleteButton;
            }

            set
            {
                grdAuthors.AutoGenerateDeleteButton = value;
            }
        }

        #endregion

        protected void Page_Load(object sender, EventArgs e)
        {
            if (Session["SignedOnUser"] != null)
            {
                _SignedOnUser = (Account.SimpleUserStructure)Session["SignedOnUser"];
            }
            else
            {
                // We shouldn't be on this page so however we got here, reject
                Server.Transfer("Account/UnauthorisedPage.aspx", true);
            }
        }

        public void Initialize()
        {
            AllowRecordSorting = true;
            AllowRecordDeleting = true;
            AllowRecordEditing = true;
            AllowEditInDetailsView = true;

            ShowFooterInsertControls(false);
        }


        protected void ShowFooterInsertControls(bool bShowControls)
        {
            lbtnInsertAuthor.Visible = bShowControls;
            lbtnCancelInsertAuthor.Visible = bShowControls;
            grdAuthors.ShowFooter = bShowControls;
            lbtnAddNewAuthor.Visible = (bShowControls == false);
        }

        protected void valDOB_ServerValidate(Object source, System.Web.UI.WebControls.ServerValidateEventArgs args)
        {
            CustomValidator cv = (CustomValidator)source;
            GridViewRow gvr = (GridViewRow)cv.NamingContainer;
            TextBox txtDOB = (TextBox)gvr.FindControl("txtDOB");

            CultureInfo culture;
            DateTimeStyles styles;
            DateTime dteDOB;

            culture = CultureInfo.CurrentCulture;
            styles = DateTimeStyles.AssumeLocal;

            if (txtDOB.Text != null)
            {
                txtDOB.Text.Trim();
                if (txtDOB.Text != "")
                {
                    if (!DateTime.TryParse(txtDOB.Text, culture, styles, out dteDOB))
                    {
                        cv.ErrorMessage = "The date of birth can be left blank but if entered must be a valid date.";
                        args.IsValid = false;
                    }
                }
            }
        }

        private int GetGridViewRowAuthorID(GridViewRow row)
        {
            int _AuthorID = 0;

            Label _ctl = (Label)row.FindControl("lblAuthorID");
            if (_ctl == null)
            {
                throw new Exception("AuthorID: could not find AuthorID control!");
            }

            _AuthorID = Convert.ToInt32(_ctl.Text);
            return _AuthorID;
        }

        protected void lbtnAddNewAuthor_Click(object sender, EventArgs e)
        {
            ShowFooterInsertControls(true);
        }

        protected void lbtnInsertAuthor_Click(object sender, EventArgs e)
        {

            Page.Validate(); // Have to do this manually for some reason as CausesValidation not working in the footer

            if (Page.IsValid)
            {
                SqlDataSource Authors = SqlDataSourceAuthors;
                GridViewRow gvrInsertRow = grdAuthors.FooterRow;

                Authors.InsertParameters["FirstName"].DefaultValue = (GetGridViewControlValue(gvrInsertRow, "txtFirstName") != string.Empty) ? GetGridViewControlValue(gvrInsertRow, "txtFirstName") : "";
                Authors.InsertParameters["LastName"].DefaultValue = (GetGridViewControlValue(gvrInsertRow, "txtLastName") != string.Empty) ? GetGridViewControlValue(gvrInsertRow, "txtLastName") : "";
                Authors.InsertParameters["DateOfBirth"].DefaultValue = GetGridViewControlValue(gvrInsertRow, "txtDOB");
                Authors.InsertParameters["Sex"].DefaultValue = GetGridViewControlValue(gvrInsertRow, "ddlSex");
               
                Authors.Insert();

                ShowFooterInsertControls(false);
            }
        }

        private string GetGridViewControlValue(GridViewRow row, string sControlName)
        {
            string sFieldValue = string.Empty;

            Control gridEditControl = row.FindControl(sControlName);

            if (gridEditControl == null)
            {
                throw new Exception("GetGridViewRowTextValue: could not find " + sControlName + " control!");
            }

            if (gridEditControl is TextBox)
            {
                TextBox txtEditControl = (TextBox)gridEditControl;
                sFieldValue = txtEditControl.Text.Trim();
                return sFieldValue;
            }

            if (gridEditControl is CheckBox)
            {
                CheckBox chkEditControl = (CheckBox)gridEditControl;
                sFieldValue = chkEditControl.Checked.ToString();
                return sFieldValue;
            }

            if (gridEditControl is DropDownList)
            {
                DropDownList ddlEditControl = (DropDownList)gridEditControl;
                sFieldValue = ddlEditControl.SelectedValue;
                return sFieldValue;
            }

            return "";

        }

        protected void lbtnCancelInsertAuthor_Click(object sender, EventArgs e)
        {
            ShowFooterInsertControls(false);
        }

        public Dictionary<Boolean, string> SexText()
        {
            if (_dctSexText == null)
            {
                _dctSexText = new Dictionary<Boolean, string>();
            }

            if (_dctSexText.Count == 0)
            {
                _dctSexText.Add(true, "Female");
                _dctSexText.Add(false, "Male");
            }

            return _dctSexText;
        }

        protected void grdAuthors_RowDataBound(object sender, GridViewRowEventArgs e)
        {
            if (e.Row.RowType == DataControlRowType.DataRow)
            {
                SqlDataSource SqlDataSourceAuthorBooks = (SqlDataSource)e.Row.FindControl("SqlDataSourceAuthorBooks");
                SqlDataSourceAuthorBooks.SelectParameters["AuthorID"].DefaultValue = e.Row.Cells[1].Text;
            }
        }
    }
}